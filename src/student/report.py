def _transfer_loss(metrics: dict) -> str:
    blocks = metrics.get("cross_subject_transfer", {})
    if not blocks:
        return "an unknown amount of"
    within = metrics.get("primary_regression", {}).get("r2", 0)
    worst = min(block["regression"]["r2"] for block in blocks.values())
    return f"up to {within - worst:.2f}"


# --------------------------------------------------------------------------- #
# Model card
# --------------------------------------------------------------------------- #
def build_model_card(metrics: dict, summary: dict) -> str:
    primary = metrics.get("primary_regression", {})
    primary_cls = metrics.get("primary_classification", {})
    dataset = metrics.get("dataset", {})
    leakage = {row["scenario"]: row for row in metrics.get("leakage_table", [])}

    def leakage_row(name: str) -> str:
        block = leakage.get(name, {})
        r2 = block.get("regression_r2", 0)
        auc = block.get("classification_auc", 0)
        return f"| {name} | {r2:.3f} | {auc:.3f} |"

    return f"""# Model Card — Student Grade Early-Warning Model

## Overview
| Field | Value |
| --- | --- |
| Version | 0.1.0 |
| Task | Regression (G3, 0–20) and pass/fail classification (G3 ≥ 10) |
| Algorithm | `{metrics.get('scenarios', {}).get('no_grades', {}).get('regression_model', 'n/a')}` |
| Trained | {metrics.get('generated_at', 'n/a')} |
| Data | UCI Student Performance, {dataset.get('rows', 0):,} student-subject records |
| Features | No prior grades (early-warning setting) |

## Intended use
Teaching and portfolio analysis of regression and classification on small tabular data,
plus a worked example of grade leakage. **Not** for admissions, streaming, discipline or
any decision about a student. Predictions describe group patterns from two Portuguese
schools in 2005–2006.

## Performance
### Final grade (regression)
| Metric | Value |
| --- | --- |
| R² | {primary.get('r2', 0):.3f} |
| RMSE | {primary.get('rmse', 0):.2f} |
| MAE | {primary.get('mae', 0):.2f} |

### Pass/fail (classification)
| Metric | Value |
| --- | --- |
| ROC AUC | {primary_cls.get('roc_auc', 0):.3f} |
| F1 | {primary_cls.get('f1', 0):.3f} |
| Precision | {primary_cls.get('precision', 0):.3f} |
| Recall | {primary_cls.get('recall', 0):.3f} |

## Leakage warning
| Scenario | R² | AUC |
| --- | --- | --- |
{leakage_row('no_grades')}
{leakage_row('with_g1')}
{leakage_row('with_g1_g2')}

The high-R² variant requires grades that only exist late in the course. Deploying it
would leak the outcome and produce a model that cannot be used when help is still
possible.

## Limitations
- Two schools, two subjects, one academic year; no external validation.
- Grade distributions differ by subject; a pooled model needs the subject indicator.
- 0–20 grades are a coarse ordinal scale treated here as interval.
- No information on teaching quality, class size, or prior attainment before G1.

## Ethical considerations
- Risk scores must never be shown to students as forecasts of their ability.
- Any intervention should be supportive, optional and evaluated for differential impact
  across the family-background variables that drive the model.
"""


